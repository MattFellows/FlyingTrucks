"""Shield sphere mesh and see-through shield material, used by FlyingCombatComponent."""
import math
import os

import unreal


def write_sphere_obj(path, rings=24, segs=48, radius=100.0):
    lines = ["# Shield sphere, generated by Scripts/combat_assets.py", "vt 0 0"]
    for r in range(rings + 1):
        th = math.pi * r / rings
        for s in range(segs):
            ph = 2 * math.pi * s / segs
            n = (math.sin(th) * math.cos(ph), math.sin(th) * math.sin(ph), math.cos(th))
            lines.append("v %.4f %.4f %.4f" % tuple(radius * c for c in n))
            lines.append("vn %.5f %.5f %.5f" % n)
    for r in range(rings):
        for s in range(segs):
            a, b = r * segs + s + 1, r * segs + (s + 1) % segs + 1
            c, d = a + segs, b + segs
            if r > 0:
                lines.append("f %d/1/%d %d/1/%d %d/1/%d" % (a, a, c, c, b, b))
            if r < rings - 1:
                lines.append("f %d/1/%d %d/1/%d %d/1/%d" % (b, b, c, c, d, d))
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


def build(folder, source_dir, asset_tools, eal, save, log):
    obj = os.path.join(source_dir, "SM_Shield.obj")
    write_sphere_obj(obj)
    t = unreal.AssetImportTask()
    for key, value in (("filename", obj), ("destination_path", folder), ("destination_name", "SM_Shield"),
                       ("automated", True), ("replace_existing", True), ("save", True)):
        t.set_editor_property(key, value)
    asset_tools.import_asset_tasks([t])
    mesh = eal.load_asset(folder + "/SM_Shield")
    if mesh is None:
        raise RuntimeError("Shield import failed")
    log("Shield mesh extent %s" % (mesh.get_bounds().box_extent,))

    path = folder + "/M_Shield"
    if eal.does_asset_exist(path):
        mat = eal.load_asset(path)
    else:
        mat = asset_tools.create_asset("M_Shield", folder, unreal.Material, unreal.MaterialFactoryNew())
        mat.set_editor_property("blend_mode", unreal.BlendMode.BLEND_TRANSLUCENT)
        mat.set_editor_property("shading_model", unreal.MaterialShadingModel.MSM_UNLIT)
        mat.set_editor_property("two_sided", True)
        mel = unreal.MaterialEditingLibrary
        color = mel.create_material_expression(mat, unreal.MaterialExpressionVectorParameter, -700, 0)
        color.set_editor_property("parameter_name", "Color")
        color.set_editor_property("default_value", unreal.LinearColor(0.1, 0.5, 1.0, 1.0))
        strength = mel.create_material_expression(mat, unreal.MaterialExpressionScalarParameter, -700, 200)
        strength.set_editor_property("parameter_name", "Intensity")
        strength.set_editor_property("default_value", 4.0)
        glow = mel.create_material_expression(mat, unreal.MaterialExpressionMultiply, -400, 50)
        mel.connect_material_expressions(color, "", glow, "A")
        mel.connect_material_expressions(strength, "", glow, "B")
        mel.connect_material_property(glow, "", unreal.MaterialProperty.MP_EMISSIVE_COLOR)
        opacity = mel.create_material_expression(mat, unreal.MaterialExpressionScalarParameter, -700, 400)
        opacity.set_editor_property("parameter_name", "Opacity")
        opacity.set_editor_property("default_value", 0.3)
        rim = mel.create_material_expression(mat, unreal.MaterialExpressionFresnel, -700, 550)
        rim.set_editor_property("exponent", 3.0)
        rim.set_editor_property("base_reflect_fraction", 0.12)
        fade = mel.create_material_expression(mat, unreal.MaterialExpressionMultiply, -400, 450)
        mel.connect_material_expressions(opacity, "", fade, "A")
        mel.connect_material_expressions(rim, "", fade, "B")
        mel.connect_material_property(fade, "", unreal.MaterialProperty.MP_OPACITY)
        mel.recompile_material(mat)
        log("Created " + path)
    save(mat)
    mesh.set_material(0, mat)
    save(mesh)
